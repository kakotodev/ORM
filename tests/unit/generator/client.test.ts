import { readFileSync } from "node:fs";
import { createSqliteAdapter } from "../../../src/adapters/sqlite.js";
import { sqliteDialect } from "../../../src/dialects/sqlite.js";
import { ConfigError } from "../../../src/errors.js";
import { generateClient } from "../../../src/generator/client.js";
import { loadSchema } from "../../../src/schema/index.js";
import { indexSchema } from "../../../src/schema/ir.js";
import { BLOG_SCHEMA, minimalSchema } from "../../helpers/schemas.js";

function fixture(name: string): string {
  // Fixed fixture names only, not user input.
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  return readFileSync(new URL(`../../fixtures/generated/blog/${name}`, import.meta.url), "utf8");
}

/** The JSON literal assigned to `schema` in a generated index.js. */
function schemaLiteral(js: string): string {
  const marker = "const schema = ";
  const start = js.indexOf(marker) + marker.length;
  return js.slice(start, js.lastIndexOf("};") + 1);
}

describe("generateClient", () => {
  it("matches the committed fixture (run npm run fixtures:update after intended changes)", () => {
    const out = generateClient(loadSchema(BLOG_SCHEMA), { runtimeImport: "../../../../src/index.js" });
    expect(out["index.js"]).toBe(fixture("index.js"));
    expect(out["index.d.ts"]).toBe(fixture("index.d.ts"));
  });

  it("emits the runtime import, the schema as JSON and createClient only", () => {
    const ir = loadSchema(BLOG_SCHEMA);
    const js = generateClient(ir)["index.js"];
    expect(js.startsWith('// Generated by mini-orm. Do not edit.\nimport { createRuntimeClient } from "mini-orm";\n')).toBe(true);
    expect(JSON.parse(schemaLiteral(js))).toEqual(ir);
    expect(js).toContain("export function createClient(options) { return createRuntimeClient(schema, options); }\n");
    expect(js).not.toContain("\r");
  });

  it("embeds the schema only as JSON and never inlines raw schema text", () => {
    const evil = minimalSchema('model A { id Int @id\n s String @default("\\"; process.exit(1); //") }');
    const { "index.js": js, "index.d.ts": dts } = generateClient(loadSchema(evil));
    expect(js).not.toMatch(/^[^"]*process\.exit/m);
    expect(() => {
      JSON.parse(schemaLiteral(js));
    }).not.toThrow();
    expect(dts).not.toContain("process.exit");
  });

  it("rejects a suspicious runtimeImport", () => {
    expect(() => generateClient(loadSchema(BLOG_SCHEMA), { runtimeImport: 'x"; import("evil' })).toThrow(ConfigError);
    expect(() => generateClient(loadSchema(BLOG_SCHEMA), { runtimeImport: "" })).toThrow(ConfigError);
    expect(() => generateClient(loadSchema(BLOG_SCHEMA), { runtimeImport: "a\nb" })).toThrow(ConfigError);
  });

  it("rejects schemas whose generated type names would collide", () => {
    const schema = minimalSchema("enum AScalars {\n X\n}\n\nmodel A { id Int @id }");
    expect(() => generateClient(loadSchema(schema))).toThrow(ConfigError);
  });

  it("types compound uniques, optional relations and createMany without connect", () => {
    const schema = minimalSchema(
      [
        "model A {\n  id Int @id @default(autoincrement())\n  x Int\n  y String\n  b B?\n  @@unique([x, y])\n}",
        "model B {\n  id String @id @default(uuid())\n  a A? @relation(fields: [aId], references: [id], onDelete: SetNull)\n  aId Int? @unique\n}",
      ].join("\n\n"),
    );
    const dts = generateClient(loadSchema(schema))["index.d.ts"];
    expect(dts).toContain("export type AWhereUnique = { id: number } | { x_y: { x: number; y: string } };");
    expect(dts).toContain("b: { model: \"B\"; list: false; nullable: true };");
    expect(dts).toContain("export type BWhereUnique = { id: string } | { aId: number };");
    expect(dts).toContain(
      "} & ({ aId?: number | null; a?: never } | { a?: { connect: AWhereUnique }; aId?: never });",
    );
    expect(dts).toMatch(/export type BCreateManyInput = \{\n {2}id\?: string;\n {2}aId\?: number \| null;\n\};/);
  });

  it("the generated client works at runtime", async () => {
    const { createClient } = await import("../../fixtures/generated/blog/index.js");
    const adapter = createSqliteAdapter({ url: "file::memory:" });
    await adapter.executeScript(sqliteDialect.createTables(indexSchema(loadSchema(BLOG_SCHEMA))));
    const db = createClient({ adapter });
    await db.user.create({ data: { email: "gen@x" } });
    expect(await db.user.count()).toBe(1);
    await db.$disconnect();
  });
});
