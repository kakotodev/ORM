import { ConfigError } from "../errors.js";
import type { EnumField, ModelIR, RelationField, ScalarField, SchemaIR } from "../schema/ir.js";

export interface GenerateOptions {
  /** Module specifier the generated client imports the runtime from. */
  runtimeImport: string;
}

export interface GeneratedClient {
  "index.js": string;
  "index.d.ts": string;
}

const HEADER = "// Generated by mini-orm. Do not edit.";
const RUNTIME_IMPORT = /^[@a-zA-Z0-9_./-]+$/;
/** Namespace of the runtime types in index.d.ts; `$` cannot appear in schema identifiers, so it never collides. */
const RT = "$runtime";

type ColumnField = ScalarField | EnumField;

const RESULT_TYPES: Readonly<Record<ScalarField["type"], string>> = {
  Int: "number",
  BigInt: "bigint",
  Float: "number",
  Decimal: "string",
  String: "string",
  Boolean: "boolean",
  DateTime: "Date",
  Json: `${RT}.JsonValue`,
  Bytes: "Uint8Array",
};

const UNORDERABLE: ReadonlySet<ScalarField["type"]> = new Set(["Json", "Bytes", "Decimal"]);

function columns(model: ModelIR): ColumnField[] {
  return model.fields.filter((f): f is ColumnField => f.kind !== "relation");
}

function relations(model: ModelIR): RelationField[] {
  return model.fields.filter((f): f is RelationField => f.kind === "relation");
}

function resultType(field: ColumnField): string {
  const base = field.kind === "enum" ? field.enumName : RESULT_TYPES[field.type];
  return field.nullable ? `${base} | null` : base;
}

/** Non-null value accepted on input (BigInt also takes a safe-integer number). */
function valueInput(field: ColumnField): string {
  if (field.kind === "enum") return field.enumName;
  return field.type === "BigInt" ? "bigint | number" : RESULT_TYPES[field.type];
}

/** Input type of a data field. The top level of a non-nullable Json value cannot be null. */
function inputType(field: ColumnField): string {
  if (field.kind === "scalar" && field.type === "Json") return field.nullable ? RESULT_TYPES.Json : `${RT}.JsonInput`;
  const base = valueInput(field);
  return field.nullable ? `${base} | null` : base;
}

const COMPARABLE: ReadonlySet<ScalarField["type"]> = new Set(["Int", "BigInt", "Float", "DateTime"]);

/** A direct value or an operator object, with the operators the runtime allows for the field type. */
function filterType(field: ColumnField): string | undefined {
  if (field.kind === "scalar" && field.type === "Json") return undefined;
  const value = valueInput(field);
  const direct = field.nullable ? `${value} | null` : value;
  if (field.kind === "scalar" && field.type === "String") {
    return `${direct} | ${RT}.StringFilter${field.nullable ? "<null>" : ""}`;
  }
  const ops = field.kind === "scalar" && COMPARABLE.has(field.type) ? "ComparableFilter" : "EqualityFilter";
  return `${direct} | ${RT}.${ops}<${value}${field.nullable ? ", null" : ""}>`;
}

function isRequiredOnCreate(field: ColumnField): boolean {
  return !(field.nullable || field.default !== undefined || (field.kind === "scalar" && field.updatedAt));
}

function isAutoincrementId(model: ModelIR, field: ColumnField): boolean {
  return field.name === model.primaryKey && field.kind === "scalar" && field.default?.kind === "autoincrement";
}

function objectType(props: readonly string[]): string {
  return props.length === 0 ? "{}" : `{\n${props.map((p) => `  ${p};\n`).join("")}}`;
}

function inlineObject(props: readonly string[]): string {
  return `{ ${props.join("; ")} }`;
}

function prop(name: string, optional: boolean, type: string): string {
  return `${name}${optional ? "?" : ""}: ${type}`;
}

function fieldMap(model: ModelIR): Map<string, ColumnField> {
  return new Map(columns(model).map((f) => [f.name, f]));
}

/** Owning-side n-1 relations: their foreign keys are set either directly or through `connect`. */
function owned(model: ModelIR): { relation: RelationField; fks: ColumnField[] }[] {
  const byName = fieldMap(model);
  return relations(model)
    .filter((r) => r.fields.length > 0)
    .map((relation) => ({
      relation,
      fks: relation.fields.map((name) => byName.get(name)).filter((f): f is ColumnField => f !== undefined),
    }));
}

function whereUniqueType(model: ModelIR): string {
  const byName = fieldMap(model);
  const options: string[] = [];
  const seen = new Set<string>();
  const single = (name: string): void => {
    const field = byName.get(name);
    if (field === undefined || seen.has(name)) return;
    seen.add(name);
    options.push(inlineObject([prop(name, false, valueInput(field))]));
  };
  single(model.primaryKey);
  for (const field of columns(model)) if (field.isUnique) single(field.name);
  for (const names of model.uniques) {
    const [only] = names;
    if (names.length === 1 && only !== undefined) {
      single(only);
      continue;
    }
    const parts = names.map((name) => {
      const field = byName.get(name);
      return prop(name, false, field === undefined ? "never" : valueInput(field));
    });
    options.push(inlineObject([prop(names.join("_"), false, inlineObject(parts))]));
  }
  return options.length === 0 ? "never" : options.join(" | ");
}

type InputMode = "create" | "createMany" | "update";

function inputTypeOf(model: ModelIR, mode: InputMode): string {
  const relationParts = owned(model);
  const fkNames = new Set(relationParts.flatMap((r) => r.fks.map((f) => f.name)));
  const withConnect = mode !== "createMany";
  const settable = (field: ColumnField): boolean =>
    mode === "update" ? field.name !== model.primaryKey : !isAutoincrementId(model, field);
  const optional = (field: ColumnField): boolean => mode === "update" || !isRequiredOnCreate(field);

  const base = columns(model)
    .filter((f) => settable(f) && !(withConnect && fkNames.has(f.name)))
    .map((f) => prop(f.name, optional(f), inputType(f)));
  if (!withConnect) return objectType(base);

  const unions = relationParts.map(({ relation, fks }) => {
    const keys = fks.filter(settable);
    const required = mode !== "update" && keys.some((f) => !optional(f));
    const none = (names: readonly string[]): string[] => names.map((name) => prop(name, true, "never"));
    const byKey = [...keys.map((f) => prop(f.name, optional(f), inputType(f))), ...none([relation.name])];
    const connect = inlineObject([prop("connect", false, `${relation.target}WhereUnique`)]);
    const byConnect = [prop(relation.name, !required, connect), ...none(keys.map((f) => f.name))];
    return `(${inlineObject(byKey)} | ${inlineObject(byConnect)})`;
  });
  return [objectType(base), ...unions].join(" & ");
}

function relationDefs(model: ModelIR): string {
  const props = relations(model).map((r) =>
    prop(r.name, false, inlineObject([`model: ${JSON.stringify(r.target)}`, `list: ${String(r.list)}`, `nullable: ${String(r.nullable)}`])),
  );
  return props.length === 0 ? "{}" : `{\n${props.map((p) => `      ${p};\n`).join("")}    }`;
}

function orderable(model: ModelIR): string {
  const names = columns(model)
    .filter((f) => f.kind === "enum" || !UNORDERABLE.has(f.type))
    .map((f) => JSON.stringify(f.name));
  return names.length === 0 ? "never" : names.join(" | ");
}

/** Every exported name of index.d.ts; a duplicate would make the declaration file invalid. */
function checkNames(schema: SchemaIR, suffixes: readonly string[]): void {
  const names = new Set(["TypeMapDef", "Delegates", "DbClient", "createClient"]);
  const add = (name: string): void => {
    if (names.has(name)) throw new ConfigError("Schema names collide with generated type names");
    names.add(name);
  };
  for (const e of schema.enums) add(e.name);
  for (const m of schema.models) for (const suffix of suffixes) add(`${m.name}${suffix}`);
}

const MODEL_TYPES = ["Scalars", "Filters", "WhereUnique", "CreateInput", "CreateManyInput", "UpdateInput"] as const;

function modelTypes(model: ModelIR): string {
  const n = model.name;
  const filters = columns(model).flatMap((f) => {
    const type = filterType(f);
    return type === undefined ? [] : [prop(f.name, true, type)];
  });
  return [
    `export type ${n}Scalars = ${objectType(columns(model).map((f) => prop(f.name, false, resultType(f))))};`,
    `export type ${n}Filters = ${objectType(filters)};`,
    `export type ${n}WhereUnique = ${whereUniqueType(model)};`,
    `export type ${n}CreateInput = ${inputTypeOf(model, "create")};`,
    `export type ${n}CreateManyInput = ${inputTypeOf(model, "createMany")};`,
    `export type ${n}UpdateInput = ${inputTypeOf(model, "update")};`,
  ].join("\n\n");
}

function typeMapEntry(model: ModelIR): string {
  const n = model.name;
  return [
    `  ${n}: {`,
    `    scalars: ${n}Scalars;`,
    `    relations: ${relationDefs(model)};`,
    `    filters: ${n}Filters;`,
    `    whereUnique: ${n}WhereUnique;`,
    `    create: ${n}CreateInput;`,
    `    createMany: ${n}CreateManyInput;`,
    `    update: ${n}UpdateInput;`,
    `    orderable: ${orderable(model)};`,
    "  };",
  ].join("\n");
}

function declarations(schema: SchemaIR, runtimeImport: string): string {
  checkNames(schema, MODEL_TYPES);
  const enums = schema.enums.map((e) => {
    const values = e.values.map((v) => JSON.stringify(v));
    return `export type ${e.name} = ${values.length === 0 ? "never" : values.join(" | ")};`;
  });
  const delegates = schema.models.map((m) => `  ${m.delegate}: ${JSON.stringify(m.name)};`);
  const sections = [
    `${HEADER}\nimport type * as ${RT} from ${JSON.stringify(runtimeImport)};`,
    ...enums,
    ...schema.models.map(modelTypes),
    `export type TypeMapDef = {\n${schema.models.map(typeMapEntry).join("\n")}\n};`,
    `export type Delegates = {\n${delegates.join("\n")}\n};`,
    `export type DbClient = ${RT}.Client<TypeMapDef, Delegates>;`,
    `export declare function createClient(options?: ${RT}.ClientOptions): DbClient;`,
  ];
  return `${sections.join("\n\n")}\n`;
}

/**
 * Emits the client for `schema`: index.js embeds the IR as a JSON literal (no other schema text is ever
 * written into code) and index.d.ts declares the typed client.
 */
export function generateClient(schema: SchemaIR, options: Partial<GenerateOptions> = {}): GeneratedClient {
  const runtimeImport = options.runtimeImport ?? "mini-orm";
  if (typeof runtimeImport !== "string" || !RUNTIME_IMPORT.test(runtimeImport)) {
    throw new ConfigError("Invalid runtimeImport");
  }
  const js = [
    HEADER,
    `import { createRuntimeClient } from ${JSON.stringify(runtimeImport)};`,
    "",
    `const schema = ${JSON.stringify(schema, null, 2)};`,
    "",
    "export function createClient(options) { return createRuntimeClient(schema, options); }",
    "",
  ].join("\n");
  return { "index.js": js, "index.d.ts": declarations(schema, runtimeImport) };
}
